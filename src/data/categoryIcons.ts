/**
 * Resolves a category name or slug to its proper icon path in /All Icons New/.
 * Always ignores backend image URLs in megamenu and uses the brand icon set.
 */
export const getCategoryIconPath = (nameOrSlug?: string): string => {
  if (!nameOrSlug) return '/All Icons New/All Icons-11.png';
  const clean = nameOrSlug.toLowerCase().trim();

  // Direct match
  if (CATEGORY_ICON_PATHS[clean]) {
    return CATEGORY_ICON_PATHS[clean];
  }

  // Normalized alphanumeric match
  const normalizedKey = clean.replace(/[^a-z0-9]/g, '');
  for (const [key, iconPath] of Object.entries(CATEGORY_ICON_PATHS)) {
    if (key.replace(/[^a-z0-9]/g, '') === normalizedKey) {
      return iconPath;
    }
  }

  // Substring match
  for (const [key, iconPath] of Object.entries(CATEGORY_ICON_PATHS)) {
    if (clean.includes(key) || key.includes(clean)) {
      return iconPath;
    }
  }

  // Fallback icon (General Mix Lots)
  return '/All Icons New/All Icons-11.png';
};

